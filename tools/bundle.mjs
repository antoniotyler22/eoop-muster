// Joins the app's scripts into one file (app.bundle.js) so the phone loads one script instead of a chain of five.
// Edit the source files listed below, then run:  npm run bundle
// CI fails if app.bundle.js is out of date (npm test checks it).
import fs from "node:fs";
import path from "node:path";
import * as acorn from "acorn";

const root = path.resolve(new URL("..", import.meta.url).pathname);
// Order matters: later files patch functions defined in earlier ones.
export const SOURCES = [
  "app.js",
  "v11.js",
  "v12.js",
  "hub.js",
  "v13.js",
  "features/errors.js",
  "features/pro-sync.js",
  "features/escalate.js",
  "features/import.js",
  "features/report.js",
  "features/geo.js",
  "features/integrations.js",
  "features/cleanup.js",
  "features/newdots.js",
  "features/invite.js",
  "features/team.js",
  "features/feedseen.js",
  "features/tour.js",
  "features/tiles17.js",
  "features/simple.js",
  "features/wow.js",
  "features/es.js",
  "features/live.js",
  "features/account.js",
  "features/teams.js",
  "features/visitors.js",
  "features/contacts.js",
  "features/people-delete.js",
];

export function build() {
  let out = "/* Accounted For: generated by tools/bundle.mjs from " + SOURCES.join(", ") + ". Do not edit; edit the sources. */\n";
  for (const f of SOURCES) {
    const src = fs.readFileSync(path.join(root, f), "utf8");
    acorn.parse(src, { ecmaVersion: "latest", sourceType: "script" }); // each file must parse on its own
    out += "\n/* ===== " + f + " ===== */\n" + src.replace(/\s*$/, "") + "\n";
  }
  out += "\nwindow.__appReady=true;\n";
  acorn.parse(out, { ecmaVersion: "latest", sourceType: "script" }); // and together (catches clashing top-level names)
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const out = build();
  const file = path.join(root, "app.bundle.js");
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (cur !== out) { console.error("app.bundle.js is out of date. Run: npm run bundle"); process.exit(1); }
    console.log("app.bundle.js is up to date");
  } else {
    fs.writeFileSync(file, out);
    console.log("app.bundle.js written (" + Math.round(out.length / 1024) + " KB from " + SOURCES.length + " files)");
  }
}
