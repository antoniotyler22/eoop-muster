/* The board's recovery code is stored encrypted with a key only this function knows. */
async function vaultKey() {
  const raw = await crypto.subtle.digest("SHA-256", te.encode("accounted-for-hub:" + (Deno.env.get("HUB_SECRET") || SRK)));
  return crypto.subtle.importKey("raw", raw, "AES-GCM", false, ["encrypt", "decrypt"]);
}
const b64 = (u: Uint8Array) => btoa(String.fromCharCode(...u));
const unb64 = (s: string) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
async function seal(code: string) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv }, await vaultKey(), te.encode(code)));
  return b64(iv) + "." + b64(ct);
}
async function unseal(s: string) {
  const [iv, ct] = s.split(".");
  return new TextDecoder().decode(await crypto.subtle.decrypt({ name: "AES-GCM", iv: unb64(iv) }, await vaultKey(), unb64(ct)));
}

