/* ---------- one board ---------- */
async function runOne(job: any) {
  const C = makeCore();
  const code = await unseal(job.ct);
  const K = await C.codeKeys(code);
  const rows = await SB.rpc("backup_get", { p_id: K.id, p_key: K.wk });
  const r = rows && rows[0];
  if (!r) return { err: "Backup not found. Turn the server hub off and on again from the OIC phone." };
  const R = await C.openBlob(K, r.ct);
  C.load(R);
  const S = C.state();
  if (S.source === "sample") return { ver: +r.ver, err: "", note: "sample roster" };
  const before = C.sig(C.syncObj());
  if (S.board) { await C.livePollCal(); await C.livePollBoard(); await C.rpPublish(false); }
  if (S.coRep) await C.coPush(false);
  const errs = [S.board && S.board.err, S.board && S.board.rerr, S.coRep && S.coRep.err].filter(Boolean);
  if (C.sig(C.syncObj()) === before) return { ver: +r.ver, err: errs.join(" · ").slice(0, 200), saved: false };
  try {
    const v = await SB.rpc("backup_put", { p_id: K.id, p_key: K.wk, p_ct: await C.sealObj(K, C.syncObj()), p_base: +r.ver });
    return { ver: +v, err: errs.join(" · ").slice(0, 200), saved: true };
  } catch (e) {
    if (/conflict/.test(String(e.message || e))) return { ver: +r.ver, err: "", saved: false, note: "phone saved first; retry next minute" };
    throw e;
  }
}

async function runAll() {
  const t0 = Date.now();
  let jobs: any[];
  try { jobs = await rest("hub_jobs?select=id,ct,seen_at,ver,ent_id,pro_ents(revoked,expires_at,env)&order=ran_at.asc.nullsfirst"); }
  catch { jobs = await rest("hub_jobs?select=id,ct,seen_at,ver&order=ran_at.asc.nullsfirst"); } // SQL part 20 not run yet
  const out = { ran: 0, phone: 0, saved: 0, errors: 0, paused: 0 };
  for (const j of jobs || []) {
    if (Date.now() - t0 > BUDGET_MS) break;
    // Boards turned on with Pro pause when that subscription ends (older boards with no subscription keep running).
    const pe = j.ent_id ? j.pro_ents : null;
    if (j.ent_id && (!pe || pe.revoked || (pe.expires_at && Date.parse(pe.expires_at) < Date.now() - (!pe.env || pe.env === "Production" || pe.env === "live" ? 864e5 : 0)))) {
      out.paused++;
      await rest("hub_jobs?id=eq." + encodeURIComponent(j.id), { method: "PATCH", body: JSON.stringify({ ran_at: new Date().toISOString(), err: "Pro ended, so the server hub is paused. Renew Pro to restart it." }), headers: { Prefer: "return=minimal" } }).catch(() => {});
      continue;
    }
    if (j.seen_at && Date.now() - Date.parse(j.seen_at) < PHONE_MS) { out.phone++; continue; }
    let res: any;
    try { res = await runOne(j); } catch (e) { res = { err: String(e.message || e).slice(0, 200) }; }
    out.ran++; if (res.saved) out.saved++; if (res.err) out.errors++;
    const patch: any = { ran_at: new Date().toISOString(), err: res.err || null };
    if (res.ver) patch.ver = res.ver;
    if (res.saved) patch.saved_at = patch.ran_at;
    await rest("hub_jobs?id=eq." + encodeURIComponent(j.id), { method: "PATCH", body: JSON.stringify(patch), headers: { Prefer: "return=minimal" } }).catch(() => {});
  }
  return out;
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: cors });
  if (req.method !== "POST") return json({ error: "POST only" }, 405);
  let body: any = {};
  try { body = await req.json(); } catch { /* empty */ }
  try {
    if (body.ping) {
      let db = false; try { await rest("hub_jobs?select=id&limit=1"); db = true; } catch { /* table missing */ }
      return json({ ok: 1, hub: 1, db });
    }
    if (body.op === "on") {
      const C = makeCore();
      const code = C.normCode(body.code);
      if (code.length !== 24) return json({ error: "Bad code." }, 400);
      const K = await C.codeKeys(code);
      const v = await SB.rpc("backup_ver", { p_id: K.id, p_key: K.wk });
      if (v == null) return json({ error: "No backup for this board yet. Tap Back up now first." }, 404);
      // The server hub runs every minute on our servers, so it's a Pro feature (HUB_REQUIRE_PRO=0 turns the check off).
      let ent: string | null = null;
      if (typeof body.pro === "string" && body.pro) {
        try { ent = await SB.rpc("pro_ent_for", { p_tok: body.pro, p_feed: null, p_mk: null }); } catch { ent = null; }
      }
      if (!ent && (Deno.env.get("HUB_REQUIRE_PRO") ?? "1") !== "0") return json({ error: "The server hub is part of Accounted For Pro.", pro: true }, 402);
      const rec: any = { id: K.id, ct: await seal(code), seen_at: new Date().toISOString(), err: null };
      if (ent) rec.ent_id = ent;
      const put = (r: any) => rest("hub_jobs?on_conflict=id", { method: "POST", body: JSON.stringify(r), headers: { Prefer: "resolution=merge-duplicates,return=minimal" } });
      try { await put(rec); } catch (e) { if (!rec.ent_id || !/ent_id/.test(String(e.message || e))) throw e; delete rec.ent_id; await put(rec); }
      return json({ ok: 1 });
    }
    if (body.op === "run") {
      const cfg = await rest("hub_cfg?select=token&id=eq.1");
      const tok = cfg && cfg[0] && cfg[0].token;
      if (!tok || req.headers.get("x-hub-token") !== tok) return json({ error: "not allowed" }, 403);
      return json(await runAll());
    }
    return json({ error: "bad request" }, 400);
  } catch (e) {
    const t = String(e.message || e);
    if (/hub_jobs|hub_cfg|schema cache|does not exist/i.test(t)) return json({ error: "Server hub isn't set up yet. Run SQL part 18." }, 503);
    return json({ error: t.slice(0, 200) }, 500);
  }
});
